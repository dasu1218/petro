import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('admin reviews promotion dates and cannot publish an invalid window', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const editor = page.locator('.product-settings-editor')
  const schedule = editor.getByRole('region', { name: 'Promotion schedule preview' })
  await expect(schedule).toContainText('Promotion disabled')
  await editor.getByRole('checkbox', { name: 'Enable a percentage discount', exact: true }).check()
  await editor.getByLabel('Promotion label', { exact: true }).fill('Summer offer')
  await expect(schedule).toContainText('Starts immediately when saved; runs until disabled')
  await editor.getByLabel('Start time (optional)', { exact: true }).fill('2030-06-02T10:00')
  await editor.getByLabel('End time (optional)', { exact: true }).fill('2030-06-01T10:00')
  await expect(schedule).toContainText('Promotion end must be after its start')
  await editor.getByRole('button', { name: 'Save product', exact: true }).click()
  expect(monitor.savedProducts).toEqual([])
  await editor.getByLabel('End time (optional)', { exact: true }).fill('2030-06-03T10:00')
  await expect(schedule).toContainText('Save product to publish this schedule')
  await editor.getByRole('button', { name: 'Save product', exact: true }).click()
  await expect.poll(() => monitor.savedProducts.length).toBe(1)
  expect(new Date(monitor.savedProducts[0].promotion.endsAt).getTime()).toBeGreaterThan(new Date(monitor.savedProducts[0].promotion.startsAt).getTime())
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
