import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('new product form explains native field failures and recovers to submission', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  const creations = []
  await page.route('**/api/products', async (route) => {
    if (route.request().method() !== 'POST') return route.fallback()
    creations.push(route.request().postDataJSON())
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Creation unavailable' }) })
  })
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const form = page.locator('.new-product-form')
  await form.getByRole('textbox', { name: 'Product name', exact: true }).fill('Test shampoo')
  const slug = form.getByRole('textbox', { name: /^Product URL name/ })
  await slug.fill('INVALID URL')
  await form.getByRole('textbox', { name: 'Description', exact: true }).fill('Gentle care')
  await form.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('250ml')
  const price = form.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true })
  await price.fill('1000')
  const create = form.getByRole('button', { name: 'Create product', exact: true })
  await create.click()
  await expect(form.getByRole('alert')).toContainText('Product URL name:')
  await expect(slug).toBeFocused()
  expect(creations).toEqual([])
  await slug.fill('test-shampoo')
  await price.fill('0')
  await create.click()
  await expect(form.getByRole('alert')).toContainText('Price (LKR) 1:')
  await expect(price).toBeFocused()
  expect(creations).toEqual([])
  await price.fill('1000')
  await create.click()
  await expect.poll(() => creations.length).toBe(1)
  await expect(form.getByRole('alert')).toHaveText('Creation unavailable')
  await expect(form.getByRole('textbox', { name: 'Product name', exact: true })).toHaveValue('Test shampoo')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
