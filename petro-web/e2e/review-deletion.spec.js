import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
const ownReview = { id: 'own-review', authorName: 'Customer Tester', rating: 4, comment: 'My published review' }

test('review deletion can be cancelled with focus restored, then explicitly confirmed', async ({ page }) => {
  const monitor = await mockStore(page, 'customer', { ownReview })
  await page.goto('/products/care-product-1')
  const reviews = page.locator('#product-reviews')
  const trigger = reviews.getByRole('button', { name: 'Delete my review', exact: true })
  await expect(reviews.getByRole('textbox', { name: 'Your review', exact: true })).toHaveValue('My published review')
  await trigger.click()
  const confirmation = reviews.getByRole('group', { name: 'Confirm review deletion', exact: true })
  const keep = confirmation.getByRole('button', { name: 'Keep my review', exact: true })
  await expect(keep).toBeFocused()
  expect(monitor.reviewRequests.filter((request) => request.startsWith('DELETE'))).toHaveLength(0)
  await keep.click()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await keep.press('Escape')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await confirmation.getByRole('button', { name: 'Confirm delete review', exact: true }).click()
  await expect(reviews.getByText('Your review was deleted.', { exact: true })).toBeVisible()
  await expect(reviews.getByRole('textbox', { name: 'Your review', exact: true })).toHaveValue('')
  await expect(trigger).toHaveCount(0)
  expect(monitor.reviewRequests.filter((request) => request.startsWith('DELETE'))).toEqual(['DELETE /reviews/care-product-1'])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('failed review deletion retains the review and supports confirmation retry', async ({ page }) => {
  const monitor = await mockStore(page, 'customer', { ownReview, failFirstReviewDelete: true })
  await page.goto('/products/care-product-1')
  const reviews = page.locator('#product-reviews')
  await reviews.getByRole('button', { name: 'Delete my review', exact: true }).click()
  const confirm = reviews.getByRole('button', { name: 'Confirm delete review', exact: true })
  await confirm.click()
  await expect(reviews.getByRole('alert')).toContainText('Review could not be deleted. Try again.')
  await expect(reviews.getByRole('textbox', { name: 'Your review', exact: true })).toHaveValue('My published review')
  await expect(confirm).toBeEnabled()
  await confirm.click()
  await expect(reviews.getByText('Your review was deleted.', { exact: true })).toBeVisible()
  await expect(reviews.getByRole('textbox', { name: 'Your review', exact: true })).toHaveValue('')
  expect(monitor.reviewRequests.filter((request) => request.startsWith('DELETE'))).toHaveLength(2)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
