import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'

test('login and registration password visibility controls preserve values without submitting', async ({ page }) => {
  const monitor = await mockStore(page)
  await page.goto('/login')
  const password = page.getByLabel('Password', { exact: true })
  await password.fill('ExamplePass123!')
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Show password', exact: true }).click()
  await expect(password).toHaveAttribute('type', 'text')
  await expect(password).toHaveValue('ExamplePass123!')
  await expect(page.getByRole('button', { name: 'Hide password', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Hide password', exact: true }).press('Enter')
  await expect(password).toHaveAttribute('type', 'password')
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/register')
  await password.fill('ExamplePass123!')
  const confirm = page.getByLabel('Confirm password', { exact: true })
  await confirm.fill('ExamplePass123!')
  await page.getByRole('button', { name: 'Show confirm password', exact: true }).click()
  await expect(confirm).toHaveAttribute('type', 'text')
  await expect(password).toHaveAttribute('type', 'password')
  await expect(confirm).toHaveValue('ExamplePass123!')
  await expect(password).toHaveAttribute('autocomplete', 'new-password')
  await expect(page).toHaveURL(/\/register$/)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('account password controls independently reveal current, new and confirmation fields', async ({ page }) => {
  const monitor = await mockStore(page, 'customer')
  await page.goto('/account')
  const form = page.locator('.password-change-form')
  for (const label of ['Current password', 'New password', 'Confirm new password']) {
    const input = form.getByLabel(label, { exact: true })
    await input.fill('ExamplePass123!')
    await form.getByRole('button', { name: `Show ${label.toLowerCase()}`, exact: true }).click()
    await expect(input).toHaveAttribute('type', 'text')
    await form.getByRole('button', { name: `Hide ${label.toLowerCase()}`, exact: true }).click()
    await expect(input).toHaveAttribute('type', 'password')
    await expect(input).toHaveValue('ExamplePass123!')
  }
  const profile = page.locator('.profile-form')
  await profile.getByLabel('Email', { exact: true }).fill('updated@example.test')
  const current = profile.getByLabel('Current password', { exact: true })
  await current.fill('ExamplePass123!')
  await profile.getByRole('button', { name: 'Show current password', exact: true }).click()
  await expect(current).toHaveAttribute('type', 'text')
  await expect(form.getByLabel('Current password', { exact: true })).toHaveAttribute('type', 'password')
  await expect(page).toHaveURL(/\/account$/)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
