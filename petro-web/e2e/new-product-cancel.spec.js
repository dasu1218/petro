import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('new product cancel preserves edited drafts until explicit discard', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const open = page.getByRole('button', { name: 'Add new product', exact: true })
  await open.click()
  const name = page.locator('.new-product-form').getByRole('textbox', { name: 'Product name', exact: true })
  await name.fill('Unpublished shampoo')
  await page.getByRole('spinbutton', { name: 'Initial stock 1', exact: true }).fill('12')
  const cancel = page.getByRole('button', { name: 'Cancel', exact: true })
  await cancel.click()
  const confirmation = page.getByRole('region', { name: 'Discard new product draft' })
  const keep = confirmation.getByRole('button', { name: 'Keep editing' })
  await expect(keep).toBeFocused()
  await keep.click()
  await expect(confirmation).toHaveCount(0)
  await expect(cancel).toBeFocused()
  await expect(name).toHaveValue('Unpublished shampoo')
  await expect(page.getByRole('spinbutton', { name: 'Initial stock 1', exact: true })).toHaveValue('12')
  await cancel.click()
  await keep.press('Escape')
  await expect(confirmation).toHaveCount(0)
  await expect(cancel).toBeFocused()
  await cancel.click()
  await confirmation.getByRole('button', { name: 'Discard draft', exact: true }).click()
  await expect(name).toHaveCount(0)
  await open.click()
  await expect(name).toHaveValue('')
  await expect(page.getByRole('spinbutton', { name: 'Initial stock 1', exact: true })).toHaveValue('0')
  await cancel.click()
  await expect(name).toHaveCount(0)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
test('size-only changes are protected when cancelling product creation', async ({ page }) => {
  await mockStore(page, 'admin')
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  await page.getByRole('button', { name: 'Add another size', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Discard new product draft' })).toBeVisible()
})
