import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
async function openCheckout(page) {
  await page.goto('/products/care-product-2')
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click()
  await page.getByRole('button', { name: 'Cart, 1 item', exact: true }).click()
  await page.getByRole('link', { name: 'Continue to checkout', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Care, delivered to your door.', exact: true })).toBeVisible()
}
async function fillAddress(page) {
  await page.getByLabel('Phone number').fill('0771234567')
  await page.getByLabel('Street address').fill('12 Test Road')
  await page.getByLabel('City', { exact: false }).fill('Colombo')
  await page.getByLabel('Postal code').fill('00700')
}
test('checkout validates an address then confirms an express COD order and clears the cart', async ({ page }, info) => {
  const monitor = await mockStore(page, 'customer')
  await openCheckout(page)
  await page.getByRole('button', { name: 'Review checkout', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Check the highlighted delivery details')
  await expect(page.locator('input[name="phone"]')).toBeFocused()
  await expect(page.getByRole('button', { name: 'Place Cash on Delivery order', exact: true })).toHaveCount(0)
  await fillAddress(page)
  await page.getByRole('radio', { name: /Express delivery/ }).check()
  await page.getByRole('button', { name: 'Review checkout', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review your delivery', exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: info.outputPath('checkout-review.png'), fullPage: true })
  await page.getByRole('button', { name: 'Place Cash on Delivery order', exact: true }).click()
  await expect(page).toHaveURL(/\/orders\/507f1f77bcf86cd799439011$/)
  await expect(page.getByRole('heading', { name: 'Thank you for your order.', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cart, 0 items', exact: true })).toBeVisible()
  expect(monitor.orderRequests).toHaveLength(1)
  expect(monitor.orderRequests[0]).toMatchObject({ deliveryMethod: 'express', paymentMethod: 'cod', expectedTotal: 1750, shippingAddress: { city: 'Colombo', country: 'Sri Lanka' } })
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
test('an uncertain order response retries the same payload and ID without a second order', async ({ page }) => {
  const monitor = await mockStore(page, 'customer', { failFirstOrderResponse: true })
  await openCheckout(page)
  await fillAddress(page)
  await page.getByRole('button', { name: 'Review checkout', exact: true }).click()
  await page.getByRole('button', { name: 'Place Cash on Delivery order', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('order response is unavailable')
  await expect(page.getByRole('button', { name: 'Cart, 1 item', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Retry original order', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Thank you for your order.', exact: true })).toBeVisible()
  expect(monitor.orderRequests).toHaveLength(2)
  expect(monitor.orderRequests[1]).toEqual(monitor.orderRequests[0])
  expect(monitor.orders.size).toBe(1)
  await expect(page.getByRole('button', { name: 'Cart, 0 items', exact: true })).toBeVisible()
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
test('an empty cart cannot submit an order', async ({ page }) => {
  const monitor = await mockStore(page, 'customer')
  await page.goto('/checkout')
  await expect(page.getByRole('heading', { name: 'Your cart is empty', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review checkout', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Place Cash on Delivery order', exact: true })).toHaveCount(0)
  expect(monitor.orderRequests).toHaveLength(0)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
