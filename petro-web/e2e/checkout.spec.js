test('customers can copy order and courier references and print hides copy controls', async ({ page }) => {
  const monitor = await mockStore(page, 'customer')
  await openCheckout(page)
  await fillAddress(page)
  await page.getByRole('button', { name: 'Review checkout', exact: true }).click()
  await page.getByRole('button', { name: 'Place Cash on Delivery order', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Thank you for your order.', exact: true })).toBeVisible()
  for (const order of monitor.orders.values()) { order.status = 'shipped'; order.tracking = { carrier: 'Test courier', number: 'PETRO-TRACK-123', url: 'https://courier.example.test/track' } }
  await page.getByRole('button', { name: 'Refresh order updates', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Copy tracking reference', exact: true })).toBeVisible()
  await page.evaluate(() => {
    window.copiedReferences = []
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (value) => { window.copiedReferences.push(value) } } })
  })
  const orderCopy = page.getByRole('button', { name: 'Copy order reference', exact: true })
  const trackingCopy = page.getByRole('button', { name: 'Copy tracking reference', exact: true })
  await orderCopy.click()
  await expect(orderCopy.locator('..').getByRole('status')).toHaveText('Reference copied.')
  await trackingCopy.click()
  await expect(trackingCopy.locator('..').getByRole('status')).toHaveText('Reference copied.')
  expect(await page.evaluate(() => window.copiedReferences)).toEqual(['507f1f77bcf86cd799439011', 'PETRO-TRACK-123'])
  await page.emulateMedia({ media: 'print' })
  await expect(orderCopy).toBeHidden()
  await expect(trackingCopy).toBeHidden()
  await expect(page.locator('.order-tracking')).toContainText('PETRO-TRACK-123')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('blocked clipboard access retains the order reference and allows retry', async ({ page }) => {
  const monitor = await mockStore(page, 'customer')
  await openCheckout(page)
  await fillAddress(page)
  await page.getByRole('button', { name: 'Review checkout', exact: true }).click()
  await page.getByRole('button', { name: 'Place Cash on Delivery order', exact: true }).click()
  const copy = page.getByRole('button', { name: 'Copy order reference', exact: true })
  await expect(copy).toBeVisible()
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Permission denied') } } }))
  await copy.click()
  await expect(copy.locator('..').getByRole('status')).toContainText('Select and copy the reference above')
  await expect(copy).toBeEnabled()
  await expect(page.locator('.order-detail-page')).toContainText('Order reference: 507f1f77bcf86cd799439011')
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => {} } }))
  await copy.click()
  await expect(copy.locator('..').getByRole('status')).toHaveText('Reference copied.')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
