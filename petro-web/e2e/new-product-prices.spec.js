import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('new product price preview follows draft sizes and validates prices', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const preview = page.getByRole('region', { name: 'Product price preview', exact: true })
  await expect(preview).toContainText('Create product to publish')
  await expect(preview).toContainText('Enter whole LKR prices')
  await page.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true }).fill('1250')
  await expect(preview.getByRole('row').filter({ hasText: 'Size 1' }).getByRole('cell')).toHaveText(['LKR 1,250', 'LKR 1,250', 'LKR 0'])
  await page.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('250ml')
  await expect(preview.getByRole('rowheader', { name: '250ml' })).toBeVisible()
  await page.getByRole('button', { name: 'Add another size', exact: true }).click()
  await page.getByRole('textbox', { name: 'Size label 2', exact: true }).fill('250ml')
  await page.getByRole('spinbutton', { name: 'Price (LKR) 2', exact: true }).fill('2000')
  await expect(preview.getByRole('rowheader', { name: '250ml', exact: true })).toHaveCount(2)
  await page.getByRole('textbox', { name: 'Size label 2', exact: true }).fill('500ml')
  await page.getByRole('spinbutton', { name: 'Price (LKR) 2', exact: true }).fill('1.5')
  await expect(preview.getByRole('table')).toHaveCount(0)
  await page.getByRole('spinbutton', { name: 'Price (LKR) 2', exact: true }).fill('2000')
  await expect(preview.getByRole('row').filter({ hasText: '500ml' }).getByRole('cell')).toHaveText(['LKR 2,000', 'LKR 2,000', 'LKR 0'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Remove size 2', exact: true }).click()
  await expect(preview.getByRole('rowheader', { name: '500ml' })).toHaveCount(0)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
