import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('product URL suggestions are explicit, editable and previewed before creation', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const name = page.getByRole('textbox', { name: 'Product name', exact: true })
  const slug = page.getByRole('textbox', { name: /^Product URL name/ })
  const preview = page.getByRole('region', { name: 'Product URL preview' })
  const suggest = preview.getByRole('button', { name: 'Suggest URL from name' })
  await expect(suggest).toBeDisabled()
  await name.fill('Café & Pet Shampoo!')
  await expect(slug).toHaveValue('')
  await suggest.click()
  await expect(slug).toHaveValue('cafe-pet-shampoo')
  await expect(preview).toContainText('Preview: /products/cafe-pet-shampoo')
  await slug.fill('my-custom-product')
  await name.fill('Different name')
  await expect(slug).toHaveValue('my-custom-product')
  await expect(preview).toContainText('/products/my-custom-product')
  await slug.fill('INVALID URL')
  await expect(preview).toContainText('Enter a valid URL name')
  await suggest.click()
  await expect(slug).toHaveValue('different-name')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
