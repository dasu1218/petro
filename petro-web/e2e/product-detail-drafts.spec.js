import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'

test('admin product details can be discarded and a successful save becomes the new draft baseline', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const editor = page.locator('.product-details-editor')
  const name = editor.getByRole('textbox', { name: 'Product name', exact: true })
  const save = editor.getByRole('button', { name: 'Save product details', exact: true })
  await expect(save).toBeDisabled()
  await name.fill('Unpublished product title')
  await expect(editor.getByText('Unpublished product details. Save to publish or discard your edits.', { exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'Discard product detail changes', exact: true }).click()
  await expect(name).toHaveValue('Care Product 1')
  await expect(save).toBeDisabled()
  expect(monitor.productDetailsRequests).toEqual([])
  await name.fill('Saved product title')
  const badges = editor.getByRole('textbox', { name: /^Badges \(optional, comma-separated\)/ })
  await badges.fill('Care, Soft, Care')
  await save.click()
  await expect(editor.getByText('Product details saved.', { exact: true })).toBeVisible()
  await expect(save).toBeDisabled()
  await expect(badges).toHaveValue('Care, Soft')
  await name.fill('Another unpublished title')
  await editor.getByRole('button', { name: 'Discard product detail changes', exact: true }).click()
  await expect(name).toHaveValue('Saved product title')
  expect(monitor.productDetailsRequests).toHaveLength(1)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('failed product-detail saves keep the draft available for retry or discard', async ({ page }) => {
  const monitor = await mockStore(page, 'admin', { failFirstProductDetailsSave: true })
  await page.goto('/admin/products')
  const editor = page.locator('.product-details-editor')
  const name = editor.getByRole('textbox', { name: 'Product name', exact: true })
  await name.fill('Retry product title')
  const save = editor.getByRole('button', { name: 'Save product details', exact: true })
  await save.click()
  await expect(editor.getByRole('alert')).toContainText('Product details could not be saved. Try again.')
  await expect(name).toHaveValue('Retry product title')
  await expect(save).toBeEnabled()
  await expect(editor.getByRole('button', { name: 'Discard product detail changes', exact: true })).toBeEnabled()
  await save.click()
  await expect(editor.getByText('Product details saved.', { exact: true })).toBeVisible()
  await expect(save).toBeDisabled()
  expect(monitor.productDetailsRequests).toHaveLength(2)
  expect(monitor.productDetailsRequests[1]).toEqual(monitor.productDetailsRequests[0])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
