import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('admin previews regular and discounted prices without publishing changes', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const editor = page.locator('.product-settings-editor')
  const preview = editor.getByRole('region', { name: 'Product price preview', exact: true })
  const row = preview.getByRole('row').filter({ hasText: '250ml' })
  await expect(row.getByRole('cell')).toHaveText(['LKR 1,000', 'LKR 1,000', 'LKR 0'])
  await editor.getByRole('checkbox', { name: 'Enable a percentage discount', exact: true }).check()
  await editor.getByRole('spinbutton', { name: 'Discount (%)', exact: true }).fill('25')
  await expect(row.getByRole('cell')).toHaveText(['LKR 1,000', 'LKR 750', 'LKR 250'])
  await editor.getByRole('spinbutton', { name: '250ml', exact: true }).fill('101')
  await expect(row.getByRole('cell')).toHaveText(['LKR 101', 'LKR 76', 'LKR 25'])
  await editor.getByRole('checkbox', { name: 'Enable a percentage discount', exact: true }).uncheck()
  await expect(row.getByRole('cell')).toHaveText(['LKR 101', 'LKR 101', 'LKR 0'])
  expect(monitor.savedProducts).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
test('invalid draft prices and discounts hide preview numbers until corrected', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const editor = page.locator('.product-settings-editor')
  const preview = editor.getByRole('region', { name: 'Product price preview', exact: true })
  const price = editor.getByRole('spinbutton', { name: '250ml', exact: true })
  await price.fill('0')
  await expect(preview.getByRole('status')).toContainText('Enter whole LKR prices')
  await expect(preview.getByRole('table')).toHaveCount(0)
  await price.fill('1000')
  await editor.getByRole('checkbox', { name: 'Enable a percentage discount', exact: true }).check()
  const discount = editor.getByRole('spinbutton', { name: 'Discount (%)', exact: true })
  await discount.fill('95')
  await expect(preview.getByRole('status')).toContainText('between 1% and 90%')
  await discount.fill('20')
  await expect(preview.getByRole('table')).toBeVisible()
  expect(monitor.savedProducts).toEqual([])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
