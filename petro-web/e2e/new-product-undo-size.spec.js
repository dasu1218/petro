import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('undo restores the last removed size and preserves edits to remaining sizes', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const form = page.locator('.new-product-form')
  await form.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('Small')
  await form.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true }).fill('1000')
  await form.getByRole('spinbutton', { name: 'Initial stock 1', exact: true }).fill('5')
  await form.getByRole('button', { name: 'Add another size', exact: true }).click()
  await form.getByRole('textbox', { name: 'Size label 2', exact: true }).fill('Large')
  await form.getByRole('button', { name: 'Remove size 1', exact: true }).click()
  const recovery = form.getByRole('region', { name: 'Removed size recovery' })
  await expect(recovery).toContainText('Removed Small')
  await form.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('Extra large')
  await recovery.getByRole('button', { name: 'Undo remove size', exact: true }).click()
  await expect(form.getByRole('textbox', { name: 'Size label 1', exact: true })).toHaveValue('Small')
  await expect(form.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true })).toHaveValue('1000')
  await expect(form.getByRole('spinbutton', { name: 'Initial stock 1', exact: true })).toHaveValue('5')
  await expect(form.getByRole('textbox', { name: 'Size label 2', exact: true })).toHaveValue('Extra large')
  await expect(recovery).toHaveCount(0)
  await form.getByRole('button', { name: 'Remove size 2', exact: true }).click()
  await expect(recovery).toContainText('Removed Extra large')
  await recovery.getByRole('button', { name: 'Undo remove size', exact: true }).click()
  await expect(form.getByRole('textbox', { name: 'Size label 2', exact: true })).toHaveValue('Extra large')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
test('undo cannot exceed the ten-size limit', async ({ page }) => {
  await mockStore(page, 'admin')
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const form = page.locator('.new-product-form')
  const add = form.getByRole('button', { name: 'Add another size', exact: true })
  await add.click()
  await form.getByRole('button', { name: 'Remove size 2', exact: true }).click()
  for (let i = 0; i < 9; i++) await add.click()
  await expect(add).toBeDisabled()
  const undo = form.getByRole('button', { name: 'Undo remove size', exact: true })
  await expect(undo).toBeDisabled()
})
