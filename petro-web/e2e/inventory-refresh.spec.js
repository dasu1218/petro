import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'

test('admin stock refresh preserves restock drafts and retains last figures after a failed refresh', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const panel = page.getByRole('region', { name: 'Stock management', exact: true })
  await expect(panel.getByText('10 available', { exact: true })).toBeVisible()
  const quantity = panel.getByRole('spinbutton', { name: 'Quantity to add', exact: true })
  const note = panel.getByRole('textbox', { name: 'Stock addition note', exact: true })
  await quantity.fill('3')
  await note.fill('Supplier delivery draft')
  monitor.setInventoryStock(6)
  const refresh = panel.getByRole('button', { name: 'Refresh stock', exact: true })
  await refresh.click()
  await expect(panel.getByText('6 available', { exact: true })).toBeVisible()
  await expect(quantity).toHaveValue('3')
  await expect(note).toHaveValue('Supplier delivery draft')
  monitor.failInventoryReads(true)
  await refresh.click()
  await expect(panel.getByRole('alert')).toContainText('Showing the last loaded stock figures.')
  await expect(panel.getByText('6 available', { exact: true })).toBeVisible()
  await expect(quantity).toHaveValue('3')
  monitor.failInventoryReads(false)
  monitor.setInventoryStock(5)
  await refresh.click()
  await expect(panel.getByText('5 available', { exact: true })).toBeVisible()
  await expect(panel.getByRole('alert')).toHaveCount(0)
  await expect(note).toHaveValue('Supplier delivery draft')
  expect(monitor.restockRequests).toEqual([])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('refreshing an uncertain stock addition preserves its original retry payload', async ({ page }) => {
  const monitor = await mockStore(page, 'admin', { failFirstRestockResponse: true })
  await page.goto('/admin/products')
  const panel = page.getByRole('region', { name: 'Stock management', exact: true })
  await panel.getByRole('spinbutton', { name: 'Quantity to add', exact: true }).fill('3')
  await panel.getByRole('textbox', { name: 'Stock addition note', exact: true }).fill('Supplier delivery')
  await panel.getByRole('button', { name: 'Add stock', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('Stock confirmation unavailable.')
  await panel.getByRole('button', { name: 'Refresh stock', exact: true }).click()
  await expect(panel.getByText('13 available', { exact: true })).toBeVisible()
  await panel.getByRole('button', { name: 'Retry same stock addition', exact: true }).click()
  await expect(panel.getByText('3 units added to 250ml.', { exact: true })).toBeVisible()
  await expect(panel.getByText('13 available', { exact: true })).toBeVisible()
  await expect(panel.locator('.stock-history > li')).toHaveCount(1)
  expect(monitor.restockRequests).toHaveLength(2)
  expect(monitor.restockRequests[1]).toEqual(monitor.restockRequests[0])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
