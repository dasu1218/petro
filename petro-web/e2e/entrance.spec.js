import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'

test('logo entrance can be skipped and appears only once in a tab session', async ({ page }, info) => {
  const monitor = await mockStore(page)
  await page.goto('/')
  const intro = page.getByRole('dialog', { name: 'Welcome to their happy place.', exact: true })
  await expect(intro).toBeVisible()
  await expect(intro.getByRole('img', { name: 'Petro', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('brand-entrance.png'), fullPage: false, animations: 'disabled' })
  await intro.getByRole('button', { name: 'Skip introduction', exact: false }).click()
  await expect(intro).toHaveCount(0)
  await expect(page.locator('main h1')).toBeVisible()
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await page.getByRole('link', { name: 'Shop', exact: true }).click()
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await expect(intro).toHaveCount(0)
  await page.reload()
  await expect(page.locator('main h1')).toBeVisible()
  await expect(intro).toHaveCount(0)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('entrance automatically reveals the store and Escape also dismisses it', async ({ page }) => {
  const monitor = await mockStore(page)
  await page.goto('/')
  const intro = page.getByRole('dialog', { name: 'Welcome to their happy place.', exact: true })
  await expect(intro).toBeVisible()
  await expect(intro).toHaveCount(0, { timeout: 5000 })
  await page.evaluate(() => sessionStorage.removeItem('petro_welcome_seen_v1'))
  await page.reload()
  await expect(intro).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(intro).toHaveCount(0)
  await expect(page.locator('main h1')).toBeVisible()
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})

test('reduced-motion customers and direct product visits do not get an entrance', async ({ page }) => {
  const monitor = await mockStore(page)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('main h1')).toBeVisible()
  await expect(page.locator('.brand-entrance')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/products/care-product-1')
  await expect(page.getByRole('heading', { name: 'Care Product 1', exact: true })).toBeVisible()
  await expect(page.locator('.brand-entrance')).toHaveCount(0)
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
