import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('initial retail value follows price and stock drafts and hides invalid totals', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const form = page.locator('.new-product-form')
  const preview = form.getByRole('region', { name: 'Initial stock retail value' })
  await expect(preview).toContainText('Enter valid size names')
  await form.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('Small')
  const price = form.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true })
  await price.fill('1000')
  await expect(preview.getByRole('status')).toHaveText('LKR 0')
  await form.getByRole('spinbutton', { name: 'Initial stock 1', exact: true }).fill('5')
  await expect(preview.getByRole('status')).toHaveText('LKR 5,000')
  await form.getByRole('button', { name: 'Add another size', exact: true }).click()
  await form.getByRole('textbox', { name: 'Size label 2', exact: true }).fill('Large')
  await form.getByRole('spinbutton', { name: 'Price (LKR) 2', exact: true }).fill('2000')
  await form.getByRole('spinbutton', { name: 'Initial stock 2', exact: true }).fill('3')
  await expect(preview.getByRole('status')).toHaveText('LKR 11,000')
  await price.fill('1.5')
  await expect(preview.getByRole('status')).toContainText('Enter valid')
  await price.fill('1000')
  await form.getByRole('button', { name: 'Remove size 2', exact: true }).click()
  await expect(preview.getByRole('status')).toHaveText('LKR 5,000')
  await expect(preview).toContainText('not profit or expected revenue')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
