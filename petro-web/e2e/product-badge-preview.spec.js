import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('admin previews badges and corrects invalid badges before publishing', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  await page.goto('/admin/products')
  const editor = page.locator('.product-details-editor')
  const badges = editor.getByRole('textbox', { name: /^Badges \(optional, comma-separated\)/ })
  const preview = editor.getByRole('region', { name: 'Product badge preview' })
  await badges.fill('Gentle, Vegan, Gentle')
  await expect(preview.getByRole('listitem')).toHaveText(['Gentle', 'Vegan'])
  await badges.fill('a'.repeat(41))
  await expect(preview).toContainText('40 characters or fewer')
  await editor.getByRole('button', { name: 'Save product details', exact: true }).click()
  expect(monitor.productDetailsRequests).toEqual([])
  await badges.fill('One,Two,Three,Four,Five,Six,Seven')
  await expect(preview).toContainText('Use up to six badges')
  await badges.fill('Gentle, Vegan, Gentle')
  await editor.getByRole('button', { name: 'Save product details', exact: true }).click()
  await expect.poll(() => monitor.productDetailsRequests.length).toBe(1)
  expect(monitor.productDetailsRequests[0].badges).toEqual(['Gentle', 'Vegan'])
  await badges.fill('')
  await expect(preview).toContainText('No badges will be shown')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
