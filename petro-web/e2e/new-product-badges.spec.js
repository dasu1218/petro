import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('new products reject invalid badges and submit normalized badges after correction', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  const creations = []
  await page.route('**/api/products', async (route) => {
    if (route.request().method() !== 'POST') return route.fallback()
    creations.push(route.request().postDataJSON())
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Creation unavailable. Try again.' }) })
  })
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  await page.getByRole('textbox', { name: 'Product name', exact: true }).fill('New shampoo')
  await page.getByRole('textbox', { name: /^Product URL name/ }).fill('new-shampoo')
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Gentle daily care.')
  await page.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('250ml')
  await page.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true }).fill('1000')
  const badges = page.getByRole('textbox', { name: /^Badges \(optional, comma-separated\)/ })
  const preview = page.getByRole('region', { name: 'New product badge preview' })
  await badges.fill('a'.repeat(41))
  await expect(preview).toContainText('40 characters or fewer')
  await page.getByRole('button', { name: 'Create product', exact: true }).click()
  expect(creations).toEqual([])
  await badges.fill('One,Two,Three,Four,Five,Six,Seven')
  await expect(preview).toContainText('Use up to six badges')
  await page.getByRole('button', { name: 'Create product', exact: true }).click()
  expect(creations).toEqual([])
  await badges.fill(' Gentle, Vegan, Gentle, ')
  await expect(preview.getByRole('listitem')).toHaveText(['Gentle', 'Vegan'])
  await page.getByRole('button', { name: 'Create product', exact: true }).click()
  await expect.poll(() => creations.length).toBe(1)
  expect(creations[0].badges).toEqual(['Gentle', 'Vegan'])
  await expect(page.getByRole('alert')).toContainText('Creation unavailable')
  await expect(badges).toHaveValue(' Gentle, Vegan, Gentle, ')
  await badges.fill('')
  await expect(preview).toContainText('No badges will be shown')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
