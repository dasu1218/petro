import { test, expect } from '@playwright/test'
import { mockStore } from './fixtures.js'
test('new product sizes reorder with their prices and stock and submit in displayed order', async ({ page }) => {
  const monitor = await mockStore(page, 'admin')
  const creations = []
  await page.route('**/api/products', async (route) => {
    if (route.request().method() !== 'POST') return route.fallback()
    creations.push(route.request().postDataJSON())
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Creation unavailable' }) })
  })
  await page.goto('/admin/products')
  await page.getByRole('button', { name: 'Add new product', exact: true }).click()
  const form = page.locator('.new-product-form')
  await form.getByRole('textbox', { name: 'Product name', exact: true }).fill('Shampoo')
  await form.getByRole('textbox', { name: /^Product URL name/ }).fill('shampoo-new')
  await form.getByRole('textbox', { name: 'Description', exact: true }).fill('Gentle care')
  await form.getByRole('textbox', { name: 'Size label 1', exact: true }).fill('Small')
  await form.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true }).fill('1000')
  await form.getByRole('spinbutton', { name: 'Initial stock 1', exact: true }).fill('5')
  await form.getByRole('button', { name: 'Add another size', exact: true }).click()
  await form.getByRole('textbox', { name: 'Size label 2', exact: true }).fill('Large')
  await form.getByRole('spinbutton', { name: 'Price (LKR) 2', exact: true }).fill('2000')
  await form.getByRole('spinbutton', { name: 'Initial stock 2', exact: true }).fill('8')
  await expect(form.getByRole('button', { name: 'Move size 1 up', exact: true })).toBeDisabled()
  await expect(form.getByRole('button', { name: 'Move size 2 down', exact: true })).toBeDisabled()
  await form.getByRole('button', { name: 'Move size 2 up', exact: true }).click()
  await expect(form.getByRole('textbox', { name: 'Size label 1', exact: true })).toHaveValue('Large')
  await expect(form.getByRole('spinbutton', { name: 'Price (LKR) 1', exact: true })).toHaveValue('2000')
  await expect(form.getByRole('spinbutton', { name: 'Initial stock 1', exact: true })).toHaveValue('8')
  await form.getByRole('button', { name: 'Move size 1 down', exact: true }).click()
  await expect(form.getByRole('textbox', { name: 'Size label 1', exact: true })).toHaveValue('Small')
  await form.getByRole('button', { name: 'Move size 1 down', exact: true }).click()
  await form.getByRole('button', { name: 'Create product', exact: true }).click()
  await expect.poll(() => creations.length).toBe(1)
  expect(creations[0].variants).toEqual([{ label: 'Large', price: 2000, stock: 8 }, { label: 'Small', price: 1000, stock: 5 }])
  await expect(form.getByRole('alert')).toContainText('Creation unavailable')
  await expect(form.getByRole('textbox', { name: 'Size label 1', exact: true })).toHaveValue('Large')
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
