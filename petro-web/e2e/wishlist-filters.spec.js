import { test, expect } from '@playwright/test'
import { mockStore, products } from './fixtures.js'
const catalog = products.slice(0, 4).map((product, index) => ({ ...product, variants: [{ label: '250ml', price: [2000, 1000, 1500, 1300][index], stock: index === 1 ? 0 : 2 }], promotion: index === 1 || index === 2 ? { label: 'Care offer', percent: 10 } : null }))
const wishlistSlugs = [...catalog.map((p) => p.slug), 'hidden-care']
test('saved products can be sorted and searched with URL persistence without changing the wishlist', async ({ page }) => {
  const monitor = await mockStore(page, 'customer', { products: catalog, wishlistSlugs })
  await page.goto('/wishlist')
  await page.getByRole('combobox', { name: 'Sort saved products', exact: true }).selectOption('price-low')
  await expect(page.locator('.product-grid > article').first()).toContainText('Care Product 2')
  await page.getByRole('searchbox', { name: 'Search wishlist', exact: true }).fill('CARE-PRODUCT-3')
  await expect(page.locator('.product-grid > article')).toHaveCount(1)
  await expect(page.getByText('Showing 1 of 4 available saved products.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('searchbox', { name: 'Search wishlist', exact: true })).toHaveValue('CARE-PRODUCT-3')
  await expect(page.getByRole('combobox', { name: 'Sort saved products', exact: true })).toHaveValue('price-low')
  await page.getByRole('button', { name: 'Clear wishlist filters', exact: true }).click()
  await expect(page.locator('.product-grid > article')).toHaveCount(4)
  expect(monitor.wishlistRequests).toEqual([])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
test('wishlist stock and promotion filters combine while unavailable saved products remain removable', async ({ page }) => {
  const monitor = await mockStore(page, 'customer', { products: catalog, wishlistSlugs })
  await page.goto('/wishlist?stock=1&offers=1')
  await expect(page.locator('.product-grid > article')).toHaveCount(1)
  await expect(page.locator('.product-grid')).toContainText('Care Product 3')
  await expect(page.getByRole('button', { name: 'Remove hidden-care from wishlist', exact: true })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search wishlist', exact: true }).fill('missing')
  await expect(page.getByText('No saved products match your filters. Clear the filters to see your saved products.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Remove hidden-care from wishlist', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Clear wishlist filters', exact: true }).click()
  await expect(page.locator('.product-grid > article')).toHaveCount(4)
  expect(monitor.wishlistRequests).toEqual([])
  expect(monitor.errors).toEqual([])
  expect(monitor.unexpected).toEqual([])
})
